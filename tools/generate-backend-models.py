"""Generate actual schema/models from isolated original runtime evidence."""
import pathlib,json,re,sqlite3,sys
root=pathlib.Path(__file__).resolve().parent.parent
source=pathlib.Path(sys.argv[1]) if len(sys.argv)>1 else root/'evidence/backend-runtime'
schema=json.loads((source/'database-schema.json').read_text(encoding='utf8'))
dest=root/'backend/internal/model';dest.mkdir(parents=True,exist_ok=True)
database=root/'backend/internal/database';database.mkdir(parents=True,exist_ok=True)
aliases={'bo_ms':'BOM','sys_users':'User','sys_roles':'Role','sys_permissions':'Permission','sys_user_roles':'UserRole','sys_role_permissions':'RolePermission','product_spus':'ProductSPU','purchase_rf_qs':'PurchaseRFQ',**{n:'Dynamic'+''.join(p.title() for p in n.split('_')) for n in ['customer','supplier','product','warehouse','sales_order','purchase_order']}}
def camel(name):return ''.join({'id':'ID','url':'URL','uuid':'UUID','ip':'IP','api':'API','bom':'BOM','qty':'Qty'}.get(p,p[:1].upper()+p[1:]) for p in name.split('_'))
def entity(name):
 if name in aliases:return aliases[name]
 singular=name[:-3]+'y' if name.endswith('ies') else name[:-1] if name.endswith('s') and not name.endswith('ss') else name
 return camel(singular)
statements=[];buffer=''
for line in (source/'database-schema.sql').read_text(encoding='utf8').splitlines(True):
 buffer+=line
 if sqlite3.complete_statement(buffer):statements.append(buffer.strip());buffer=''
assert not buffer.strip()
statements.sort(key=lambda s:0 if s.startswith('CREATE TABLE') else 1)
sql='-- Actual exactly from the original fresh SQLite database.\n\n'+'\n\n'.join(statements)+'\n'
connection=sqlite3.connect(':memory:');connection.executescript(sql)
assert connection.execute("SELECT count(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").fetchone()[0]==len(schema)
(database/'schema.sql').write_text(sql,encoding='utf8')
(database/'schema.json').write_text(json.dumps(schema,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
manifest=[];names=set()
for table in schema:
 name=entity(table['name']);assert name not in names,name;names.add(name)
 lines=['// Code generated by tools/generate-backend-models.py from original SQLite evidence.','// Schema is actual; Go names and field types are reconstructed, not original source.','package model','','import ("encoding/json"; "time")','','var _ json.RawMessage','var _ time.Time','','type '+name+' struct {']
 for column in table['columns']:
  sqltype=column['type'].lower()
  typ={'uuid':'string','text':'string','datetime':'time.Time','date':'time.Time','numeric':'Decimal','integer':'int64','bool':'bool','real':'float64','json':'json.RawMessage','blob':'[]byte'}.get(sqltype,'string')
  if not column['notnull'] and typ not in ['json.RawMessage','[]byte']:typ='*'+typ
  tag='-' if column['name'] in ['password_hash'] else column['name']+',omitempty'
  lines.append('    '+camel(column['name'])+' '+typ+' `json:"'+tag+'" db:"'+column['name']+'"`')
 lines.extend(['}','','func ('+name+') SQLTableName() string { return "'+table['name']+'" }',''])
 (dest/(table['name']+'.go')).write_text('\n'.join(lines),encoding='utf8')
 manifest.append({'table':table['name'],'go_type':name,'columns':len(table['columns'])})
(root/'evidence/backend-models.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8')
print('Generated',len(schema),'Go model structs; verified original schema migration in SQLite.')
