export const getTemplateByIcon = (icon: string, category?: string): IndustryTemplate | undefined => {
  if (category) {
    const matchedByCategory = INDUSTRY_TEMPLATES.find(
      template => template.icon === icon && template.category === category
    );
    if (matchedByCategory) {
      return matchedByCategory;
    }
  }
  return INDUSTRY_TEMPLATES.find(template => template.icon === icon);
};
